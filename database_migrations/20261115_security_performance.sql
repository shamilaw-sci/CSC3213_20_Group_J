-- Supports the current entity schema and the former empty bootstrap schema.
-- Does not change stock quantities or infer whether historical payments were collected.
BEGIN;
DO $$ BEGIN
  IF to_regclass('users') IS NULL THEN RAISE EXCEPTION 'Use database_setup.sql for a fresh installation'; END IF;
  IF EXISTS (SELECT 1 FROM users GROUP BY lower(trim(email)) HAVING count(*)>1) THEN
    RAISE EXCEPTION 'Case-insensitive duplicate emails exist. Resolve account ownership before upgrading; no accounts were merged.';
  END IF;
  IF to_regclass('cart') IS NOT NULL AND to_regclass('carts') IS NULL THEN ALTER TABLE cart RENAME TO carts;
  ELSIF to_regclass('cart') IS NOT NULL AND to_regclass('carts') IS NOT NULL THEN
    IF EXISTS(SELECT 1 FROM cart) THEN RAISE EXCEPTION 'Both cart and carts contain legacy structures; reconcile their ownership first'; END IF;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema=current_schema() AND table_name='orders' AND column_name='stock_allocated')
     AND EXISTS(SELECT 1 FROM orders) THEN
    RAISE EXCEPTION 'Legacy order allocation state is unknown. Reconcile inventory/reservations and add verified stock_allocated values before upgrading.';
  END IF;
END $$;
